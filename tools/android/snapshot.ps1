# Collect only the active Windows host; never overwrite a Linux snapshot.
[CmdletBinding()]
param()
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) {
    throw 'This collector requires Windows. On Linux use tools/android/snapshot.sh.'
}
$repositoryRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$outputRoot = Join-Path $repositoryRoot '.codebase-memory/environments/windows'
New-Item -ItemType Directory -Force -Path $outputRoot | Out-Null
$sdkRoot = $env:ANDROID_HOME
if ([string]::IsNullOrWhiteSpace($sdkRoot)) { $sdkRoot = $env:ANDROID_SDK_ROOT }
if ([string]::IsNullOrWhiteSpace($sdkRoot)) { $sdkRoot = Join-Path $env:LOCALAPPDATA 'Android/Sdk' }

function Get-ToolPath([string]$Name) {
    $command = Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -ne $command) { return $command.Source }
    $relative = switch ($Name) {
        'adb' { 'platform-tools/adb.exe' }
        'emulator' { 'emulator/emulator.exe' }
        'sdkmanager' { 'cmdline-tools/latest/bin/sdkmanager.bat' }
        'avdmanager' { 'cmdline-tools/latest/bin/avdmanager.bat' }
        default { $null }
    }
    if ($null -ne $relative) {
        $candidate = Join-Path $sdkRoot $relative
        if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
    }
    return $null
}
function Get-ToolOutput([string]$Path, [string[]]$ToolArguments) {
    if ([string]::IsNullOrWhiteSpace($Path)) { return 'unavailable' }
    # Java writes its version to stderr. PS 5.1 wraps stderr as NativeCommandError.
    $ErrorActionPreference = 'Continue'
    try {
        $output = (& $Path @ToolArguments 2>&1 | Out-String).Trim()
        if ($LASTEXITCODE -ne 0) { return "exit ${LASTEXITCODE}: $output" }
        return $output
    } catch { return 'unavailable' }
}
$argumentsByTool = [ordered]@{
    java = @('-version'); javac = @('-version'); git = @('--version')
    node = @('--version'); npm = @('--version'); adb = @('version')
    sdkmanager = @('--version'); avdmanager = @('list', 'avd'); emulator = @('-version')
}
$tools = [ordered]@{}
foreach ($name in $argumentsByTool.Keys) {
    $path = Get-ToolPath $name
    $tools[$name] = [ordered]@{ path = $path; version = Get-ToolOutput $path $argumentsByTool[$name] }
}
$os = Get-CimInstance Win32_OperatingSystem
$cpu = Get-CimInstance Win32_Processor | Select-Object -First 1
$now = [DateTimeOffset]::UtcNow
$snapshot = [ordered]@{
    platformId = 'windows'; collectedAt = $now.ToString('o'); refreshDue = $now.AddDays(7).ToString('o')
    os = 'Windows'; distribution = $os.Caption; architecture = $os.OSArchitecture
    powershell = $PSVersionTable.PSVersion.ToString(); sdkRoot = $sdkRoot; javaHome = $env:JAVA_HOME
    virtualizationFirmwareEnabled = $cpu.VirtualizationFirmwareEnabled
    emulatorAcceleration = Get-ToolOutput (Get-ToolPath 'emulator') @('-accel-check')
    avds = Get-ToolOutput (Get-ToolPath 'emulator') @('-list-avds')
    devices = Get-ToolOutput (Get-ToolPath 'adb') @('devices', '-l')
    sdkExists = (Test-Path -LiteralPath $sdkRoot -PathType Container)
    sdkPackages = @(foreach ($part in @('platforms','build-tools','system-images')) {
        Get-ChildItem -LiteralPath (Join-Path $sdkRoot $part) -Filter source.properties -Recurse -File -ErrorAction SilentlyContinue | ForEach-Object { $_.DirectoryName }
    })
    tools = $tools
}
$json = $snapshot | ConvertTo-Json -Depth 8
# Explicit UTF-8 works identically under Windows PowerShell 5.1 and PowerShell 7.
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path $outputRoot 'environment-snapshot.json'), $json + "`n", $utf8)
$markdown = "# Local Windows environment snapshot`n`nGenerated by tools/android/snapshot.ps1; expires after seven days. Machine-local, ignored by Git.`n`n" + '```json' + "`n" + $json + "`n" + '```' + "`n"
[IO.File]::WriteAllText((Join-Path $outputRoot 'environment-snapshot.md'), $markdown, $utf8)
Write-Output "Windows snapshot: $outputRoot"
